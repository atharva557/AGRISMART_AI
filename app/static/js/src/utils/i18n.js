class I18nEngine {
  constructor() {
    this.currentLang = 'en';
    this.originalMap = new Map();
    this.STORAGE_KEY = 'agrismart-lang';
  }

  init() {
    let saved = 'en';
    try {
      saved = localStorage.getItem(this.STORAGE_KEY) || 'en';
    } catch (e) {}

    this.currentLang = saved;

    if (this.currentLang && this.currentLang !== 'en') {
      this.translatePage(this.currentLang);
    }

    this.observeDom();
  }

  setLanguage(langCode) {
    if (!langCode) langCode = 'en';
    this.currentLang = langCode;

    try {
      localStorage.setItem(this.STORAGE_KEY, langCode);
    } catch (e) {}

    this.translatePage(langCode);

    document.querySelectorAll('#global-lang-select, #advisory-assistant-lang, #assistant-lang').forEach(select => {
      if (select && select.value !== langCode) {
        select.value = langCode;
      }
    });
  }

  translatePage(lang) {
    if (!lang) lang = this.currentLang || 'en';

    const walker = document.createTreeWalker(
      document.body,
      NodeFilter.SHOW_TEXT,
      {
        acceptNode: (node) => {
          const parent = node.parentElement;
          if (!parent) return NodeFilter.FILTER_REJECT;
          const tag = parent.tagName.toLowerCase();
          if (['script', 'style', 'noscript', 'code', 'pre'].includes(tag)) {
            return NodeFilter.FILTER_REJECT;
          }
          if (parent.closest('.notranslate, [translate="no"], #global-lang-select')) {
            return NodeFilter.FILTER_REJECT;
          }
          if (!node.nodeValue || !node.nodeValue.trim()) {
            return NodeFilter.FILTER_SKIP;
          }
          return NodeFilter.FILTER_ACCEPT;
        }
      }
    );

    const nodes = [];
    while (walker.nextNode()) {
      nodes.push(walker.currentNode);
    }

    nodes.forEach(node => {
      const text = node.nodeValue.trim();
      if (!this.originalMap.has(node)) {
        this.originalMap.set(node, text);
      }

      const orig = this.originalMap.get(node);
      if (lang === 'en') {
        if (orig) node.nodeValue = node.nodeValue.replace(text, orig);
      } else if (DICTIONARY[orig] && DICTIONARY[orig][lang]) {
        node.nodeValue = node.nodeValue.replace(text, DICTIONARY[orig][lang]);
      }
    });

    document.querySelectorAll('input[placeholder], textarea[placeholder]').forEach(el => {
      const current = el.getAttribute('placeholder');
      if (!el.dataset.origPlaceholder) {
        el.dataset.origPlaceholder = current;
      }
      const orig = el.dataset.origPlaceholder;
      if (lang === 'en') {
        el.setAttribute('placeholder', orig);
      } else if (DICTIONARY[orig] && DICTIONARY[orig][lang]) {
        el.setAttribute('placeholder', DICTIONARY[orig][lang]);
      }
    });
  }

  observeDom() {
    if (this._observer) return;
    this._observer = new MutationObserver(() => {
      if (this.currentLang && this.currentLang !== 'en') {
        clearTimeout(this._debounce);
        this._debounce = setTimeout(() => this.translatePage(this.currentLang), 50);
      }
    });

    this._observer.observe(document.body, { childList: true, subtree: true });
  }
}

const I18n = new I18nEngine();

if (typeof window !== 'undefined') {
  window.I18n = I18n;
  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', () => I18n.init());
  } else {
    I18n.init();
  }
}

export default I18n;
